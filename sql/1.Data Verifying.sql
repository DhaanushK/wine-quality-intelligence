CREATE DATABASE wine_quality_intelligence;
USE wine_quality_intelligence;
SELECT DATABASE();

-- Creating a Table wine_reviews to store the 97,851 records from our deduplicated CSV
-- TRUNCATE TABLE wine_reviews;

LOAD DATA LOCAL INFILE
'D:/Masters in AI/Wine Business Intelligence Project/data/processed/wine_reviews_deduplicated.csv'
INTO TABLE wine_quality_intelligence.wine_reviews
CHARACTER SET utf8mb4
FIELDS TERMINATED BY ','
OPTIONALLY ENCLOSED BY '"'
LINES TERMINATED BY '\n'
IGNORE 1 LINES
(
    country,
    description,
    designation,
    points,
    price,
    province,
    region_1,
    region_2,
    variety,
    winery
);
DESCRIBE wine_reviews;

-- 1. Confirm the actual row count.
SELECT COUNT(*) AS total_rows
FROM wine_reviews;

-- 1. Verify total rows and missing prices
SELECT
    COUNT(*) AS total_rows,
    SUM(price IS NULL) AS missing_prices,
    SUM(price = 0) AS zero_prices,
    COUNT(price) AS non_missing_prices
FROM wine_reviews;

-- 2. Check the price range
SELECT
    MIN(price) AS minimum_price,
    MAX(price) AS maximum_price,
    ROUND(AVG(price), 2) AS average_price,
    MIN(points) AS minimum_rating,
    MAX(points) AS maximum_rating
FROM wine_reviews;

-- 3. Check for duplicate wine records
-- review_id is generated by MySQL, so exclude it.
SELECT COUNT(*) AS duplicate_record_groups
FROM (
    SELECT
        country, description, designation, points, price,
        province, region_1, region_2, variety, winery
    FROM wine_reviews
    GROUP BY
        country, description, designation, points, price,
        province, region_1, region_2, variety, winery
    HAVING COUNT(*) > 1
) AS duplicates;

-- 4. Inspect Unicode text
SELECT country, designation, province, winery
FROM wine_reviews
WHERE winery IN (
    'Domaine de la Bégude',
    'Bergström',
    'Wölffer'
);